package rangetarget.core.geometry

import kotlinx.serialization.Serializable
import kotlinx.serialization.encodeToString

/**
 * The ISSF 25 m precision / 50 m pistol target card (Krüger Best.-Nr. 3100).
 *
 * This object is the only place in the code base that holds the card's
 * dimensions. Everything else (detection, scoring, drawing, the Python test
 * tools via `test_data/card_geometry.json`) gets them from here.
 * Requirements and their source live in docs/SPEC.md; nominal values are used
 * here and ISSF tolerances are not yet modelled.
 */
object CardGeometry {
    const val NAME = "ISSF 25 m precision / 50 m pistol"

    /** Diameter of the 10 ring. */
    const val TEN_RING_DIAMETER_MM = 50.0

    /** Each ring further out adds this much to the diameter (25 mm of radius). */
    const val RING_DIAMETER_STEP_MM = 50.0

    const val HIGHEST_RING = 10
    const val LOWEST_RING = 1

    /** The black aiming area covers rings 7 to 10, so its edge is the 7 ring. */
    const val BLACK_OUTER_RING = 7

    /**
     * Paper size, sold as "55 × 52 cm". Measured on the real test photo
     * (Phase 1) as about 548 wide × 521 high with the card upright, so the
     * longer side runs left to right. Paper cut varies; use it as a guide only.
     */
    const val PAPER_WIDTH_MM = 550.0
    const val PAPER_HEIGHT_MM = 520.0

    /**
     * Small printed marks that look like holes to the detector, by centre and
     * radius in mm. Measured from the real test photo, so approximate.
     * Holes found on them are flagged as uncertain, not dropped.
     */
    val printedMarks: List<PrintedMark> = listOf(
        PrintedMark("ISSF approval logo", PointMm(-243.0, -240.0), 9.0),
    )

    val rings: IntRange = LOWEST_RING..HIGHEST_RING

    /** Diameter of ring [ring] (1..10), measured to the outside of its line. */
    fun ringDiameterMm(ring: Int): Double {
        require(ring in rings) { "Ring must be in $rings, was $ring" }
        return TEN_RING_DIAMETER_MM + (HIGHEST_RING - ring) * RING_DIAMETER_STEP_MM
    }

    fun ringRadiusMm(ring: Int): Double = ringDiameterMm(ring) / 2.0

    val blackDiameterMm: Double get() = ringDiameterMm(BLACK_OUTER_RING)
    val blackRadiusMm: Double get() = blackDiameterMm / 2.0
    val outerRingDiameterMm: Double get() = ringDiameterMm(LOWEST_RING)

    /**
     * The ring a single point lies in, or 0 outside the 1 ring.
     * A point exactly on a ring's edge counts as inside that ring.
     * This is point-based only; scoring by hole edge (see docs/SPEC-ISSUES.md,
     * item 6) is built on top of it later.
     */
    fun ringAt(radiusMm: Double): Int {
        require(radiusMm >= 0.0) { "Radius must not be negative" }
        for (ring in HIGHEST_RING downTo LOWEST_RING) {
            if (radiusMm <= ringRadiusMm(ring)) return ring
        }
        return 0
    }

    fun ringAt(point: PointMm): Int = ringAt(point.radius)

    fun isInBlack(point: PointMm): Boolean = point.radius <= blackRadiusMm

    /** The same constants as plain data, for export to the Python tools. */
    fun export(): CardGeometryExport = CardGeometryExport(
        name = NAME,
        tenRingDiameterMm = TEN_RING_DIAMETER_MM,
        ringDiameterStepMm = RING_DIAMETER_STEP_MM,
        ringDiametersMm = rings.associate { it.toString() to ringDiameterMm(it) },
        blackOuterRing = BLACK_OUTER_RING,
        blackDiameterMm = blackDiameterMm,
        paperWidthMm = PAPER_WIDTH_MM,
        paperHeightMm = PAPER_HEIGHT_MM,
    )

    fun exportJson(): String = exportJsonFormat.encodeToString(export()) + "\n"

    private val exportJsonFormat get() = rangetarget.core.RangeJson
}

/** A printed mark on the card (logo, maker's text) that the hole finder should be wary of. */
data class PrintedMark(val name: String, val centreMm: PointMm, val radiusMm: Double)

/**
 * Card constants as written to `test_data/card_geometry.json`, which the Python
 * test tools read. Generated by `rangetarget geometry`; a core test fails if
 * the checked-in file drifts from [CardGeometry].
 */
@Serializable
data class CardGeometryExport(
    val name: String,
    val tenRingDiameterMm: Double,
    val ringDiameterStepMm: Double,
    val ringDiametersMm: Map<String, Double>,
    val blackOuterRing: Int,
    val blackDiameterMm: Double,
    val paperWidthMm: Double,
    val paperHeightMm: Double,
)
